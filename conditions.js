// On doit parfois executer un code deifferent selon une condition. Pour cela, on utilise les instructions conditionnelles if, else if et else.
// Si a > b alors on affiche "Bonjour", sinon on affiche "Au revoir"

let a = 12;
let b = 14;

if (a > b)      
    {                         //Si a est plus grand que B
    console.log("Bonjour");   // On ecrit Bonjour, bloc 1
    alert("Bonjour"); 
    }
else   
    {                         // Sinon
    console.log("Au revoir"); //On ecrit Au revoir, bloc 2
    alert("Au revoir");
    }

// IMPORTANT !! Si un bloc ne contient plus d'une instruction, on peut supprimer les accolades.

